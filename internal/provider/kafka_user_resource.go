func (r *KafkaUserResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	// Prevent panic if the provider has not been configured.
	if req.ProviderData == nil {
		return
	}

	providerData, ok := req.ProviderData.(ArtieProviderData)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Resource Configure Type",
			fmt.Sprintf("Expected ArtieProviderData, got: %T. Please report this issue to the provider developers.", req.ProviderData),
		)

		return
	}

	client, err := providerData.NewOpenAPIClient()
	if err != nil {
		resp.Diagnostics.AddError("Unable to build Artie client", err.Error())
		return
	}

	r.client = client
}

func (r *KafkaUserResource) getStateData(ctx context.Context, state tfsdk.State, diagnostics *diag.Diagnostics) (tfmodels.KafkaUser, bool) {
	var stateData tfmodels.KafkaUser
	diagnostics.Append(state.Get(ctx, &stateData)...)
	return stateData, diagnostics.HasError()
}

// credentials fetches the user's password and current details. It returns HTTP 409 while the password isn't ready yet.
func (r *KafkaUserResource) credentials(ctx context.Context, user tfmodels.KafkaUser) (*openapi.RouterKafkaUserCredentialsResponse, int, error) {
	clusterUUID, userUUID := user.ClusterUUID.ValueString(), user.UUID.ValueString()
	if user.IsAdmin() {
		resp, err := r.client.KafkaAdminUserCredentialsWithResponse(ctx, clusterUUID, userUUID)
		creds, err := artieclient.JSON200(resp, err)
		return creds, statusCode(resp), err
	}
	resp, err := r.client.KafkaUserCredentialsWithResponse(ctx, clusterUUID, userUUID)
	creds, err := artieclient.JSON200(resp, err)
	return creds, statusCode(resp), err
}

func statusCode[R interface{ StatusCode() int }](resp *R) int {
	if resp == nil {
		return 0
	}
	return (*resp).StatusCode()
}

// waitForCredentials polls the credentials endpoint until the user's password is ready (it answers 409 until then).
func waitForCredentials[T any](ctx context.Context, timeout, interval time.Duration, fetch func() (*T, int, error)) (*T, error) {
	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	for {
		creds, code, err := fetch()
		if err == nil || code != http.StatusConflict {
			return creds, err
		}
		select {
		case <-ctx.Done():
			return nil, fmt.Errorf("timed out after %s waiting for the Kafka user's password: %w", timeout, err)
		case <-time.After(interval):
		}
	}
}

// findUser returns the user, or nil if it no longer exists.
func (r *KafkaUserResource) findUser(ctx context.Context, user tfmodels.KafkaUser) (*openapi.PayloadsKafkaUser, error) {
	clusterUUID, userUUID := user.ClusterUUID.ValueString(), user.UUID.ValueString()
	// An imported user has no access_profile yet, so it could be either.
	if !user.IsAdmin() {
		resp, err := r.client.KafkaUserDetailWithResponse(ctx, clusterUUID, userUUID)
		apiUser, err := artieclient.JSON200(resp, err)
		switch {
		case err == nil:
			return apiUser, nil
		case statusCode(resp) != http.StatusNotFound:
			return nil, err
		case tfmodels.IsKnown(user.AccessProfile):
			return nil, nil
		}
	}

	// Admin users are managed under /admin-users.
	resp, err := r.client.KafkaAdminUserDetailWithResponse(ctx, clusterUUID, userUUID)
	apiUser, err := artieclient.JSON200(resp, err)
	if statusCode(resp) == http.StatusNotFound {
		return nil, nil
	}
	return apiUser, err
}

func (r *KafkaUserResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var planData tfmodels.KafkaUser
	resp.Diagnostics.Append(req.Plan.Get(ctx, &planData)...)
	if resp.Diagnostics.HasError() {
		return
	}

	clusterUUID := planData.ClusterUUID.ValueString()
	var created *openapi.RouterKafkaUserCreateResponse
	var err error
	if planData.IsAdmin() {
		created, err = artieclient.JSON200(r.client.KafkaAdminUserCreateWithResponse(ctx, clusterUUID, planData.ToAPICreateAdminRequest()))
	} else {
		created, err = artieclient.JSON200(r.client.KafkaUserCreateWithResponse(ctx, clusterUUID, planData.ToAPICreateRequest()))
	}
	if err != nil {
		resp.Diagnostics.AddError("Unable to create Kafka user", err.Error())
		return
	}

	user := tfmodels.KafkaUserFromAPIModel(clusterUUID, created.KafkaUser, types.StringPointerValue(created.Password))
	if created.Password == nil || *created.Password == "" {
		// Save the user first so a failed wait doesn't leave it untracked.
		user.Password = types.StringNull()
		resp.Diagnostics.Append(resp.State.Set(ctx, user)...)

		creds, err := waitForCredentials(ctx, kafkaUserPasswordTimeout, kafkaUserPasswordInterval, func() (*openapi.RouterKafkaUserCredentialsResponse, int, error) {
			return r.credentials(ctx, user)
		})
		if err != nil {
			resp.Diagnostics.AddError("Unable to get Kafka user's password", err.Error())
			return
		}
		user = tfmodels.KafkaUserFromAPIModel(clusterUUID, creds.KafkaUser, types.StringValue(creds.Password))
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, user)...)
}

func (r *KafkaUserResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	stateData, hasError := r.getStateData(ctx, req.State, &resp.Diagnostics)
	if hasError {
		return
	}

	apiUser, err := r.findUser(ctx, stateData)
	if err != nil {
		resp.Diagnostics.AddError("Unable to read Kafka user", err.Error())
		return
	}
	if apiUser == nil {
		resp.State.RemoveResource(ctx)
		return
	}

	user := tfmodels.KafkaUserFromAPIModel(stateData.ClusterUUID.ValueString(), *apiUser, stateData.Password)
	if !tfmodels.IsKnownAndNonEmpty(user.Password) {
		// Imported, or a create that timed out waiting for the password.
		creds, _, err := r.credentials(ctx, user)
		if err != nil {
			resp.Diagnostics.AddWarning("Unable to get Kafka user's password", err.Error())
		} else {
			user.Password = types.StringValue(creds.Password)
		}
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, user)...)
}

func (r *KafkaUserResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	// Every argument forces a new user, so there is nothing to update.
	stateData, hasError := r.getStateData(ctx, req.State, &resp.Diagnostics)
	if hasError {
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, stateData)...)
}

func (r *KafkaUserResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	stateData, hasError := r.getStateData(ctx, req.State, &resp.Diagnostics)
	if hasError {
		return
	}

	clusterUUID, userUUID := stateData.ClusterUUID.ValueString(), stateData.UUID.ValueString()
	var code int
	var err error
	if stateData.IsAdmin() {
		apiResp, apiErr := r.client.KafkaAdminUserDeleteWithResponse(ctx, clusterUUID, userUUID)
		code, err = statusCode(apiResp), artieclient.CheckResponse(apiResp, apiErr)
	} else {
		apiResp, apiErr := r.client.KafkaUserDeleteWithResponse(ctx, clusterUUID, userUUID)
		code, err = statusCode(apiResp), artieclient.CheckResponse(apiResp, apiErr)
	}
	if err != nil && code != http.StatusNotFound {
		resp.Diagnostics.AddError("Unable to delete Kafka user", err.Error())
	}
}

// ImportState takes `<cluster_uuid>/<user_uuid>`. Read then fills in the rest, including the password.
func (r *KafkaUserResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	clusterUUID, userUUID, ok := strings.Cut(req.ID, "/")
	if !ok || clusterUUID == "" || userUUID == "" {
		resp.Diagnostics.AddError("Invalid import ID", fmt.Sprintf("Expected `<cluster_uuid>/<user_uuid>`, got %q.", req.ID))
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("cluster_uuid"), clusterUUID)...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("uuid"), userUUID)...)
}
